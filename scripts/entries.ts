/*
 * Writes one Userscript++ plugin entry per CC++ plugin: sites/claude/plugins/<Name>/index.ts, which
 * hands the plugin from src/plugins to the framework. src/plugins/index.ts (PLUGINS) stays the list;
 * entries for plugins no longer in it are removed. Run by `bun run build`; `--check` only reports drift.
 *
 *   bun --preload ./tests/setup.ts scripts/entries.ts [--check]
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "fs";
import { join } from "path";

import { PLUGINS } from "../src/plugins";

const DIR = "sites/claude/plugins";
const check = process.argv.includes("--check");

export function expectedEntries() {
    const source = readFileSync("src/plugins/index.ts", "utf-8");
    const paths = new Map([...source.matchAll(/^import (\w+) from "([^"]+)";$/gm)].map(m => [m[1], m[2]]));
    const list = /export const PLUGINS[^=]*=\s*\[([\s\S]*?)\];/.exec(source)?.[1] ?? "";
    const ids = list.split(",").map(s => s.trim()).filter(Boolean);
    if (ids.length !== PLUGINS.length) throw new Error(`src/plugins/index.ts lists ${ids.length} identifiers but PLUGINS has ${PLUGINS.length}`);
    return new Map(
        ids.map((id, i) => {
            const path = paths.get(id);
            if (!path) throw new Error(`No import for ${id} in src/plugins/index.ts`);
            const name = PLUGINS[i].name;
            const body = `// Generated by scripts/entries.ts from src/plugins/index.ts. Do not edit.\nimport { toFramework } from "@kernel/framework";\nimport plugin from "${path}";\n\nexport default toFramework(plugin);\n`;
            return [name, body] as const;
        }),
    );
}

const want = expectedEntries();
const have = existsSync(DIR) ? readdirSync(DIR) : [];
const drift: string[] = [];
for (const name of have) {
    if (want.has(name)) continue;
    drift.push(`stale ${name}`);
    if (!check) rmSync(join(DIR, name), { recursive: true, force: true });
}
for (const [name, body] of want) {
    const file = join(DIR, name, "index.ts");
    if (existsSync(file) && readFileSync(file, "utf-8") === body) continue;
    drift.push(`write ${name}`);
    if (!check) {
        mkdirSync(join(DIR, name), { recursive: true });
        writeFileSync(file, body);
    }
}
if (check && drift.length) {
    console.error(`Plugin entries out of date (bun run build fixes it): ${drift.join(", ")}`);
    process.exit(1);
}
console.log(`${want.size} plugin entries${drift.length ? ` (${drift.length} updated)` : ""}`);
